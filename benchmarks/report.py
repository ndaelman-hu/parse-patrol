"""Aggregate ``results.csv`` into a human-readable ``report.md``.

Reports every parser at two denominators:

* **All files** -- the naive "point the parser at every file in the upload"
  scenario. A legitimate but pessimistic number.
* **Mainfile only** -- only the single file NOMAD itself designates as the
  primary parseable output per entry. The rigorous, non-arbitrary denominator.

The gap between the two is itself a finding, as is the ``empty`` outcome: a
parser that returns a structureless model *without raising* fails silently, which
is strictly worse for an agent than an exception it could catch and route around.

Usage:
    python -m benchmarks.report --results benchmarks/results.csv --out benchmarks/report.md
"""

from __future__ import annotations

import argparse
import csv
from collections import Counter, defaultdict
from typing import Dict, List

PARSER_ORDER = ["ase", "cclib", "gaussian", "iodata"]
OUTCOMES = ["success", "empty", "error", "timeout"]


def _load(results_path: str) -> List[dict]:
    with open(results_path) as f:
        return list(csv.DictReader(f))


def _pct(num: int, den: int) -> str:
    return f"{100.0 * num / den:5.1f}%" if den else "  n/a"


def _rate_cell(num: int, den: int) -> str:
    return f"{_pct(num, den).strip()} ({num}/{den})" if den else "n/a"


def _oracle(rows: List[dict]):
    """Per-file, did ANY parser succeed? Returns (all_files, mainfiles) stats
    and the breakdown of which parser-set solves each mainfile."""
    by_file: Dict[tuple, Dict[str, str]] = defaultdict(dict)
    mainfiles = set()
    for r in rows:
        key = (r["entry_id"], r["file"])
        by_file[key][r["parser"]] = r["outcome"]
        if r["is_mainfile"] == "1":
            mainfiles.add(key)

    def union(keys):
        return sum(any(o == "success" for o in by_file[k].values()) for k in keys)

    all_keys = list(by_file)
    combos: Counter = Counter()
    for k in mainfiles:
        winners = tuple(sorted(p for p, o in by_file[k].items() if o == "success"))
        combos[winners] += 1
    return {
        "all_total": len(all_keys), "all_union": union(all_keys),
        "mf_total": len(mainfiles), "mf_union": union(mainfiles),
        "combos": combos,
    }


def build_report(rows: List[dict]) -> str:
    parsers = [p for p in PARSER_ORDER if any(r["parser"] == p for r in rows)]
    programs = sorted({r["program"] for r in rows})
    oracle = _oracle(rows)

    # ---- per-parser aggregate (all files & mainfile) --------------------------
    all_counts: Dict[str, Counter] = {p: Counter() for p in parsers}
    all_success: Dict[str, int] = defaultdict(int)
    all_energy: Dict[str, int] = defaultdict(int)
    all_total: Dict[str, int] = defaultdict(int)
    mf_success: Dict[str, int] = defaultdict(int)
    mf_energy: Dict[str, int] = defaultdict(int)
    mf_total: Dict[str, int] = defaultdict(int)
    exc_hist: Dict[str, Counter] = {p: Counter() for p in parsers}
    # per program x parser, mainfile success
    prog_mf_succ: Dict[str, Dict[str, int]] = {p: defaultdict(int) for p in parsers}
    prog_mf_tot: Dict[str, Dict[str, int]] = {p: defaultdict(int) for p in parsers}
    prog_all_succ: Dict[str, Dict[str, int]] = {p: defaultdict(int) for p in parsers}
    prog_all_tot: Dict[str, Dict[str, int]] = {p: defaultdict(int) for p in parsers}

    for r in rows:
        p = r["parser"]
        if p not in all_counts:
            continue
        outcome = r["outcome"]
        is_main = r["is_mainfile"] == "1"
        succ = outcome == "success"
        energy = r["has_energy"] == "1"
        prog = r["program"]

        all_counts[p][outcome] += 1
        all_total[p] += 1
        all_success[p] += succ
        all_energy[p] += energy
        prog_all_tot[p][prog] += 1
        prog_all_succ[p][prog] += succ
        if outcome == "error":
            exc_hist[p][r["exception_type"]] += 1
        if is_main:
            mf_total[p] += 1
            mf_success[p] += succ
            mf_energy[p] += energy
            prog_mf_tot[p][prog] += 1
            prog_mf_succ[p][prog] += succ

    lines: List[str] = []
    add = lines.append

    add("# Parser Reliability Benchmark — Multi-Parser Report")
    add("")
    add("Generated by `benchmarks/report.py` from `results.csv`. Corpus: real "
        "computational-chemistry files from the NOMAD repository, frozen in "
        "`dataset.json`.")
    add("")
    add("**Success** = the parser extracted an atomic structure (atoms + "
        "coordinates) without raising. **Empty** = no exception but no structure "
        "(a *silent* failure). **Error** = exception raised. **Timeout** = exceeded "
        "the per-file budget.")
    add("")

    # ---- headline table -------------------------------------------------------
    add("## Headline: success rate by parser")
    add("")
    add("| Parser | All files | Mainfile only | Mainfile w/ energy |")
    add("|---|---|---|---|")
    for p in parsers:
        add(f"| {p} | {_rate_cell(all_success[p], all_total[p])} "
            f"| {_rate_cell(mf_success[p], mf_total[p])} "
            f"| {_rate_cell(mf_energy[p], mf_total[p])} |")
    add("")
    add("The **All files → Mainfile** jump isolates how much of the naive "
        "failure rate is just parsers being pointed at files they never claimed "
        "to handle, versus genuine failure on the designated primary output.")
    add("")

    # ---- oracle / union -------------------------------------------------------
    add("## Oracle: best parser per file")
    add("")
    add("Upper bound for any multi-parser router: a file counts as solved if "
        "*any* of the four parsers succeeds on it.")
    add("")
    add(f"* **All files:** {_rate_cell(oracle['all_union'], oracle['all_total'])} solved by at least one parser.")
    add(f"* **Mainfile only:** {_rate_cell(oracle['mf_union'], oracle['mf_total'])} solved by at least one parser.")
    add("")
    add("Even with a perfect router, the majority of primary output files remain "
        "unparsed. The parsers that *do* succeed are largely disjoint by domain — "
        "which mainfile is solved by which parser set:")
    add("")
    add("| Winning parser set | Mainfiles |")
    add("|---|---|")
    for combo, cnt in oracle["combos"].most_common():
        label = ", ".join(combo) if combo else "*(none — no parser succeeds)*"
        add(f"| {label} | {cnt} |")
    add("")

    # ---- outcome breakdown ----------------------------------------------------
    add("## Outcome breakdown (all files)")
    add("")
    add("| Parser | " + " | ".join(o.capitalize() for o in OUTCOMES) + " | Total |")
    add("|---|" + "---|" * (len(OUTCOMES) + 1))
    for p in parsers:
        cells = " | ".join(str(all_counts[p][o]) for o in OUTCOMES)
        add(f"| {p} | {cells} | {all_total[p]} |")
    add("")
    add("The **Empty** column is the silent-failure count: structureless models "
        "returned with no exception. An agent cannot distinguish these from a "
        "genuinely empty file without inspecting the payload.")
    add("")

    # ---- per-program mainfile matrix -----------------------------------------
    add("## Success by program — mainfile only")
    add("")
    add("One primary output file per entry, as designated by NOMAD. `n/a` means "
        "no mainfile for that program was present on disk.")
    add("")
    add("| Program | " + " | ".join(parsers) + " |")
    add("|---|" + "---|" * len(parsers))
    for prog in programs:
        row = [f"| {prog} "]
        for p in parsers:
            tot = prog_mf_tot[p][prog]
            row.append(f"| {_pct(prog_mf_succ[p][prog], tot).strip() if tot else 'n/a'} "
                       f"{'(' + str(prog_mf_succ[p][prog]) + '/' + str(tot) + ')' if tot else ''}")
        add("".join(row) + "|")
    add("")

    # ---- per-program all-files matrix ----------------------------------------
    add("## Success by program — all files")
    add("")
    add("| Program | " + " | ".join(parsers) + " |")
    add("|---|" + "---|" * len(parsers))
    for prog in programs:
        row = [f"| {prog} "]
        for p in parsers:
            tot = prog_all_tot[p][prog]
            row.append(f"| {_pct(prog_all_succ[p][prog], tot).strip() if tot else 'n/a'} "
                       f"{'(' + str(prog_all_succ[p][prog]) + '/' + str(tot) + ')' if tot else ''}")
        add("".join(row) + "|")
    add("")

    # ---- failure taxonomy -----------------------------------------------------
    add("## Failure taxonomy (exception types, all files)")
    add("")
    for p in parsers:
        top = exc_hist[p].most_common(8)
        if not top:
            add(f"**{p}**: no exceptions recorded.")
            add("")
            continue
        total_err = sum(exc_hist[p].values())
        add(f"**{p}** — {total_err} exceptions:")
        add("")
        add("| Exception | Count | Share of errors |")
        add("|---|---|---|")
        for name, cnt in top:
            add(f"| {name} | {cnt} | {_pct(cnt, total_err).strip()} |")
        add("")

    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", default="benchmarks/results.csv")
    ap.add_argument("--out", default="benchmarks/report.md")
    args = ap.parse_args()

    rows = _load(args.results)
    report = build_report(rows)
    with open(args.out, "w") as f:
        f.write(report)
    print(f"Wrote {args.out} from {len(rows)} result rows.")


if __name__ == "__main__":
    main()
